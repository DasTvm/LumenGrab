// Regenerates THIRD_PARTY_LICENSES from the dependency trees.
//   JavaScript: production dependencies via `pnpm licenses list --prod --json`
//   Rust:       `cargo about` (fails on any license outside src-tauri/about.toml `accepted`)
// Requires: pnpm, `cargo install cargo-about --locked --features cli`. Run: pnpm licenses:update
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const run = (cmd, args) =>
  execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

const SEP = "=".repeat(78);

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\..*)?$/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : null;
}

function npmSection() {
  const byLicense = JSON.parse(run("pnpm", ["licenses", "list", "--prod", "--json"]));
  const groups = new Map(); // license text -> { license, packages[] }
  for (const [license, pkgs] of Object.entries(byLicense)) {
    for (const pkg of pkgs) {
      const dir = pkg.paths.find((p) => existsSync(p));
      const text =
        (dir && licenseText(dir)) ?? `(no license file shipped; declared license: ${license})`;
      const entry = groups.get(text) ?? { license, packages: [] };
      entry.packages.push(...pkg.versions.map((v) => `${pkg.name} ${v}`));
      groups.set(text, entry);
    }
  }
  return [...groups.entries()]
    .sort(([, a], [, b]) => a.license.localeCompare(b.license))
    .map(([text, { license, packages }]) =>
      [
        `=== ${license} ===`,
        "",
        "Used by:",
        ...[...new Set(packages)].sort().map((p) => `- ${p}`),
        "",
        text,
        "",
      ].join("\n"),
    )
    .join("\n");
}

function rustSection() {
  return run("cargo", [
    "about",
    "generate",
    "--manifest-path",
    "src-tauri/Cargo.toml",
    "--config",
    "src-tauri/about.toml",
    "src-tauri/about.hbs",
  ]);
}

const out = [
  "THIRD-PARTY LICENSES",
  "",
  "LumenGrab itself is licensed under the PolyForm Noncommercial License 1.0.0 (see LICENSE).",
  "It includes the third-party software listed below. Generated by `pnpm licenses:update`; do not edit by hand.",
  "",
  SEP,
  "JAVASCRIPT / TYPESCRIPT (production dependencies)",
  SEP,
  "",
  npmSection(),
  SEP,
  "RUST (crates linked into the app)",
  SEP,
  "",
  rustSection(),
].join("\n");

writeFileSync("THIRD_PARTY_LICENSES", out.replace(/\s+$/, "") + "\n");
console.log("Wrote THIRD_PARTY_LICENSES");
